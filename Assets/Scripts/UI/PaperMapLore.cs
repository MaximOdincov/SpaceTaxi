        // до 4 строк: лор тела (макс 3) + один общий факт по данным LevelAsset
        public static string[] For(CelestialBodyData body)
        {
            var lines = new List<string>(4);
            if (body != null && Notes.TryGetValue(body.DisplayName, out string[] lore))
            {
                for (int i = 0; i < lore.Length && lines.Count < 3; i++)
                    lines.Add(lore[i]);
            }
            string generic = Generic(body);
            if (lines.Count < 4 && !lines.Contains(generic))
                lines.Add(generic);
            return lines.ToArray();
        }

        private static string Generic(CelestialBodyData body)
        {
            if (body == null)
                return "карта старше меня — не всё тут сходится";
            switch (body.Type)
            {
                case BodyType.Star:
                    return "звезда: жар плавит щит, держи дистанцию";
                case BodyType.BlackHole:
                    return "тянет к центру — газ заранее";
                case BodyType.AsteroidBelt:
                    return "пролёт по краю дешевле ремонта корпуса";
                case BodyType.Planet:
                    if (body.IsHub)
                        return "последний тир сети — топливо дорогое";
                    if (body.HasFuel && body.HasRepair)
                        return "заправка и мастерская в одном месте";
                    if (body.HasFuel)
                        return "сеть работает, бак проверяй на всякий";
                    if (body.HasRepair)
                        return "мастерская чинит честно, без ночной наценки";
                    return body.Sector == Sector.Far
                        ? "дальние не балуют заправками"
                        : "пассажиров ловить у посадочного кольца";
                default:
                    return "обычное место, ничего личного";
            }
        }
